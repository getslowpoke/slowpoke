const dictionaries = { it }

/** Quello che ha scelto chi guarda, se l'ha scelto: vince su tutto e resta suo. */
function chosen() {
  try {
    return localStorage.getItem('slowpoke:locale') || ''
  } catch {
    return '' // storage non disponibile
  }
}

function fromBrowser() {
  return (navigator.language || 'en').toLowerCase().startsWith('it') ? 'it' : 'en'
}

function detect() {
  return chosen() || fromBrowser()
}

export const locale = ref(detect())

/**
 * La lingua dichiarata dal server (SLOWPOKE_LOCALE). Vale per chi non ha ancora scelto: una demo
 * pubblica si apre nella lingua del prodotto, non in quella del browser di chi passa, e il piede
 * della pagina resta li per cambiarla.
 */
export function setServerLocale(l) {
  const wanted = String(l || '').trim().slice(0, 5).toLowerCase()
  if (!wanted || chosen()) return
  if (dictionaries[wanted] || wanted === 'en') locale.value = wanted
}

export function setLocale(l) {
  locale.value = l
  try {
    localStorage.setItem('slowpoke:locale', l)
  } catch {
    /* storage unavailable */
  }
}

export function t(text, params = {}) {
  const out = dictionaries[locale.value]?.[text] ?? text
  return out.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
}
